/**
 * Convert staged CIE / CVRL CSV datasheets → offline TS tables under
 * src/engine/physics/optics/observer/data/
 *
 * Usage: node scripts/cie/convert-cie-datasheets.mjs
 * No runtime network — reads scripts/cie/raw/ only.
 */
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '../..');
const RAW = join(__dirname, 'raw');
const OUT = join(ROOT, 'src/engine/physics/optics/observer/data');

const SOURCES = {
  photopic: {
    file: 'vl1924e_1.csv',
    doi: 'https://doi.org/10.25039/CIE.DS.dktna2s3',
    cite: 'CIE 1924 photopic V(λ), 1 nm (CVRL mirror of CIE table)',
    url: 'http://www.cvrl.org/database/data/lum/vl1924e_1.csv',
  },
  scotopic: {
    file: 'scvle_1.csv',
    doi: null,
    cite: 'CIE 1951 scotopic V′(λ), 1 nm (CVRL / Wyszecki & Stiles)',
    url: 'http://www.cvrl.org/database/data/lum/scvle_1.csv',
  },
  cmf: {
    file: 'ciexyz31_1.csv',
    doi: null,
    cite: 'CIE 1931 2° colour-matching functions x̄,ȳ,z̄, 1 nm (CVRL)',
    url: 'http://www.cvrl.org/database/data/cmfs/ciexyz31_1.csv',
  },
  lms: {
    file: 'linss2_10e_1.csv',
    doi: null,
    cite: 'Stockman & Sharpe (2000) 2° cone fundamentals L,M,S — CIE 2006-compatible LMS, 1 nm (CVRL)',
    url: 'http://www.cvrl.org/database/data/cones/linss2_10e_1.csv',
  },
};

function md5(buf) {
  return createHash('md5').update(buf).digest('hex');
}

function parseCsvPairs(text, cols = 2) {
  const rows = [];
  for (const line of text.split(/\r?\n/)) {
    const t = line.trim();
    if (!t || t.startsWith('#') || t.startsWith('Wavelength')) continue;
    const parts = t.split(/[,\s]+/).filter(Boolean).map(Number);
    if (parts.length < cols || !Number.isFinite(parts[0])) continue;
    rows.push(parts.slice(0, cols));
  }
  return rows;
}

function densify(rows, valueIndex = 1) {
  const byNm = new Map();
  for (const r of rows) byNm.set(Math.round(r[0]), r[valueIndex]);
  const nms = [...byNm.keys()].sort((a, b) => a - b);
  const nmMin = nms[0];
  const nmMax = nms[nms.length - 1];
  const values = [];
  for (let nm = nmMin; nm <= nmMax; nm++) {
    values.push(byNm.has(nm) ? byNm.get(nm) : 0);
  }
  return { nmMin, nmMax, stepNm: 1, values };
}

function densifyMulti(rows, channels) {
  const byNm = new Map();
  for (const r of rows) byNm.set(Math.round(r[0]), r.slice(1, 1 + channels));
  const nms = [...byNm.keys()].sort((a, b) => a - b);
  const nmMin = nms[0];
  const nmMax = nms[nms.length - 1];
  const values = [];
  for (let nm = nmMin; nm <= nmMax; nm++) {
    const v = byNm.get(nm) ?? Array(channels).fill(0);
    for (let c = 0; c < channels; c++) values.push(v[c] ?? 0);
  }
  return { nmMin, nmMax, stepNm: 1, channels, values };
}

function sample(curve, nm) {
  if (!Number.isFinite(nm)) return 0;
  const i = Math.round(nm);
  if (i < curve.nmMin || i > curve.nmMax) {
    const edge = i < curve.nmMin ? curve.nmMin : curve.nmMax;
    return curve.values[edge - curve.nmMin] ?? 0;
  }
  return curve.values[i - curve.nmMin] ?? 0;
}

function buildMesopicM08(photopic, scotopic) {
  const nmMin = Math.max(photopic.nmMin, scotopic.nmMin);
  const nmMax = Math.min(photopic.nmMax, scotopic.nmMax);
  const m = 0.8;
  const raw = [];
  let peak = 0;
  for (let nm = nmMin; nm <= nmMax; nm++) {
    const v = m * sample(photopic, nm) + (1 - m) * sample(scotopic, nm);
    raw.push(v);
    if (v > peak) peak = v;
  }
  const values = raw.map((v) => (peak > 0 ? v / peak : 0));
  return {
    nmMin,
    nmMax,
    stepNm: 1,
    values,
    note: 'Educational blend target: normalize(0.8·V + 0.2·V′). Not a claim of CIE 191 dynamic mesopic compliance.',
  };
}

function fmtNum(n) {
  if (!Number.isFinite(n)) return '0';
  if (n === 0) return '0';
  const a = Math.abs(n);
  if (a >= 1e-4 && a < 1e6) {
    const s = n.toPrecision(8);
    return s.replace(/\.?0+$/, '').replace(/\.$/, '') || '0';
  }
  return n.toExponential(8);
}

function emitCurveTs(name, curve, extraJsDoc = '') {
  const vals = curve.values.map(fmtNum).join(', ');
  return `/**
 * Auto-generated by scripts/cie/convert-cie-datasheets.mjs — do not edit by hand.
 * ${extraJsDoc}
 */
export const ${name} = {
  nmMin: ${curve.nmMin},
  nmMax: ${curve.nmMax},
  stepNm: ${curve.stepNm},
  values: [${vals}],
} as const;
`;
}

function emitMultiTs(name, curve, channelNames, extraJsDoc = '') {
  const vals = curve.values.map(fmtNum).join(', ');
  return `/**
 * Auto-generated by scripts/cie/convert-cie-datasheets.mjs — do not edit by hand.
 * Layout: interleaved ${channelNames.join(', ')} per nm.
 * ${extraJsDoc}
 */
export const ${name} = {
  nmMin: ${curve.nmMin},
  nmMax: ${curve.nmMax},
  stepNm: ${curve.stepNm},
  channels: ${curve.channels},
  channelNames: ${JSON.stringify(channelNames)} as const,
  values: [${vals}],
} as const;
`;
}

function main() {
  mkdirSync(OUT, { recursive: true });
  mkdirSync(join(OUT, 'generated'), { recursive: true });

  const manifests = [];
  const today = new Date().toISOString().slice(0, 10);

  const photopicText = readFileSync(join(RAW, SOURCES.photopic.file));
  const scotopicText = readFileSync(join(RAW, SOURCES.scotopic.file));
  const cmfText = readFileSync(join(RAW, SOURCES.cmf.file));
  const lmsText = readFileSync(join(RAW, SOURCES.lms.file));

  const photopic = densify(parseCsvPairs(photopicText.toString('utf8'), 2));
  const scotopic = densify(parseCsvPairs(scotopicText.toString('utf8'), 2));
  const cmf = densifyMulti(parseCsvPairs(cmfText.toString('utf8'), 4), 3);
  const lms = densifyMulti(parseCsvPairs(lmsText.toString('utf8'), 4), 3);
  const mesopic = buildMesopicM08(photopic, scotopic);

  writeFileSync(join(OUT, 'generated/v-lambda-photopic.ts'), emitCurveTs('V_LAMBDA_PHOTOPIC', photopic, 'CIE 1924 V(λ).'));
  writeFileSync(join(OUT, 'generated/v-lambda-scotopic.ts'), emitCurveTs('V_LAMBDA_SCOTOPIC', scotopic, 'CIE 1951 V′(λ).'));
  writeFileSync(
    join(OUT, 'generated/v-lambda-mesopic-m08.ts'),
    emitCurveTs('V_LAMBDA_MESOPIC_M08', mesopic, mesopic.note),
  );
  writeFileSync(
    join(OUT, 'generated/cmf-cie1931-2deg.ts'),
    emitMultiTs('CMF_CIE1931_2DEG', cmf, ['xBar', 'yBar', 'zBar'], 'CIE 1931 2° CMF.'),
  );
  writeFileSync(
    join(OUT, 'generated/lms-cie2006-2deg.ts'),
    emitMultiTs('LMS_CIE2006_2DEG', lms, ['L', 'M', 'S'], 'Stockman & Sharpe 2° LMS (CIE 2006-compatible).'),
  );

  for (const [key, src] of Object.entries(SOURCES)) {
    const buf = readFileSync(join(RAW, src.file));
    manifests.push({
      id: key,
      file: src.file,
      md5: md5(buf),
      bytes: buf.length,
      cite: src.cite,
      doi: src.doi,
      url: src.url,
      staged: relative(ROOT, join(RAW, src.file)).replace(/\\/g, '/'),
    });
  }
  manifests.push({
    id: 'mesopic-m08',
    file: '(derived)',
    md5: md5(Buffer.from(JSON.stringify(mesopic.values))),
    bytes: mesopic.values.length * 8,
    cite: mesopic.note,
    doi: null,
    url: null,
    staged: 'derived from photopic + scotopic with m=0.8',
  });

  const citations = [
    '# CIE / CVRL observer datasheets — citations',
    '',
    `Converted: ${today}`,
    'Runtime: **no network** — tables live under `observer/data/generated/`.',
    '',
    '| Id | Source file | MD5 | Citation |',
    '|----|-------------|-----|----------|',
    ...manifests.map(
      (m) =>
        `| ${m.id} | \`${m.file}\` | \`${m.md5}\` | ${m.cite}${m.doi ? ` ([DOI](${m.doi}))` : ''} |`,
    ),
    '',
    '## Provenance',
    '',
    '- Raw CSV staged in `scripts/cie/raw/` (and optionally `temp/cie-datasheets/`).',
    '- Photopic / scotopic / CMF / LMS downloaded from [CVRL](http://www.cvrl.org/).',
    '- Mesopic m=0.8 is an **educational blend target** (normalize(0.8·V+0.2·V′)), not a claim of CIE 191 dynamic mesopic physiology compliance.',
    '- Engine pack-side photopic lookup may still use the legacy 390–808 table until Phase B parity gate; HumanEye uses these CIE tables.',
    '',
  ].join('\n');

  writeFileSync(join(OUT, 'CITATIONS.md'), citations);
  writeFileSync(join(OUT, 'manifest.json'), JSON.stringify({ converted: today, sources: manifests }, null, 2));

  // eslint-disable-next-line no-console
  console.log(`Wrote CIE tables → ${relative(ROOT, OUT)}`);
  for (const m of manifests) {
    // eslint-disable-next-line no-console
    console.log(`  ${m.id}: ${m.md5}`);
  }
}

main();
